      if (units) for (const unit of units) for (const factor of [1, 2, 5, 10, 20, 50, 100, 200, 500]) steps.push(unit * factor);
      else for (let exponent = -6; exponent <= 18; exponent += 1) for (const factor of [1, 2, 5]) steps.push(factor * 10 ** exponent);
      return steps;
