    // The operand table, the cost line and the small print of an operand step.
    function operandBody(step, scale) {
      const spec = step.operands(scale);
      const summed = new Set(spec.summed ?? []);
      const table = element("div", "flow-operands");
      const axesUsed = new Set();
      // what the dtype cells abbreviate (scales, reused operands), said once in the small print
      const dtypeNotes = new Set();
      let bytes = 0;
      let firstGroup = true;
      for (const [groupKey, groupLabel] of FLOW_OPERAND_GROUPS) {
        const entries = spec[groupKey];
        if (!entries?.length) continue;
        entries.forEach((entry, index) => {
          bytes += window.ATTN_FLOW_KIT.bytes(entry);
          const opensGroup = index === 0 && !firstGroup ? " opens-group" : "";
          table.append(element("div", `flow-op-group${opensGroup}`, index === 0 ? groupLabel : ""));
          const name = element("div", `flow-op-name${opensGroup}`);
          name.append(flowSymbol(entry.name));
          const shape = element("div", `flow-op-shape${opensGroup}`);
          shape.append("[");
          entry.axes.forEach((dimension, axisIndex) => {
            if (axisIndex) shape.append(", ");
            for (const atom of dimension.label.split(/[·+()/−]/)) if (atom) axesUsed.add(atom);
            // an axis the step sums over is underlined (small print: "summed over")
            const axisNode = element("span", summed.has(dimension.label) ? "flow-axis is-summed" : "flow-axis");
            const label = element("span", "flow-axis-label");
            label.append(flowSymbol(dimension.label));
            axisNode.append(label, " ", element("span", "flow-axis-value", flowAxisValue(dimension)));
            shape.append(axisNode);
          });
          shape.append("]");
          const dtypeText = entry.onChip ? "on chip" : entry.reused ? "reused" : `${entry.dtype}${entry.scale ? "+s" : ""}`;
          const dtype = element("div", `flow-op-dtype${opensGroup}${entry.onChip || entry.reused ? " is-on-chip" : ""}`, dtypeText);
          for (const note of window.ATTN_FLOW_KIT.dtypeNotes(entry)) dtypeNotes.add(note);
          table.append(name, shape, dtype);
        });
        firstGroup = false;
      }
      const tableWrap = element("div", "flow-operands-wrap");
      tableWrap.append(table);
      const cost = element("div", "flow-op-cost");
      const costItem = (label, value, emphasis) => {
        const item = element("span", `flow-cost-item${emphasis ? " is-intensity" : ""}`);
        item.append(element("span", "flow-cost-label", label), element("span", "flow-cost-value", value));
        return item;
      };
      cost.append(
        costItem("FLOPs", flowFlopsText(spec.flops)),
        costItem("Bytes", bytes ? bytesText(bytes) : "0, on chip"),
        costItem("Intensity", bytes ? `${flowIntensityText(spec.flops / bytes)} FLOP/B` : "—", true),
      );
      // small print: the axes this step uses (the sliders hold their values)
      const notes = element("div", "flow-op-notes");
      const axes = element("div", "flow-legend-axes");
      for (const [label, meaning] of flow.axes ?? []) {
        if (!axesUsed.has(label)) continue;
        const item = element("span", "flow-legend-axis");
        const symbol = element("span", "flow-axis-label");
        symbol.append(flowSymbol(label));
        item.append(symbol, " ", flowSymbol(byMode(meaning, scale.mode)));
        axes.append(item);
      }
      if (summed.size) {
        const item = element("span", "flow-legend-axis");
        item.append(element("span", "flow-axis is-summed", "underlined"), ": summed over");
        axes.append(item);
      }
      notes.append(axes);
      // only notes that explain a cell of this table ("+s", "reused"); how
      // FLOPs and bytes are counted lives in the flow files' comments
      for (const note of dtypeNotes) notes.append(symbolElement("div", "", note));
      return [tableWrap, cost, notes];
    }
    // The full-screen card opens under the clicked card (above it when the card is
    // low in the figure), kept inside the figure; its pointer marks the card.
    function positionDetail() {
      if (!openCard) return;
      const box = container.getBoundingClientRect();
      const cardBox = openCard.getBoundingClientRect();
      const width = detail.offsetWidth;
      const cardCenter = cardBox.left + cardBox.width / 2 - box.left;
      const left = Math.min(Math.max(cardCenter - width / 2, 12), box.width - width - 12);
      // + scrollTop: the full-screen box scrolls, and the detail is placed in its content
      const offsetTop = container.scrollTop - box.top;
      const height = detail.offsetHeight;
      const belowTop = cardBox.bottom + offsetTop + 14;
      const aboveTop = cardBox.top + offsetTop - height - 14;
      let below = cardBox.top - box.top < box.height / 2;
      let top = below ? belowTop : aboveTop;
      // In the full-screen box a detail sticking out of the bottom would add a
      // scrollbar: there it goes below only if it fits, else above, and is
      // clamped into the box. Inline it may overhang the text, as before.
      if (container.classList.contains("is-fullscreen")) {
        const bottomLimit = container.clientHeight - 12;
        below = belowTop + height <= bottomLimit || aboveTop < 12;
        top = Math.max(12, Math.min(below ? belowTop : aboveTop, bottomLimit - height));
      }
      detail.classList.toggle("is-above", !below);
      detail.style.left = `${left}px`;
      detail.style.top = `${top}px`;
      detail.style.setProperty("--pointer-x", `${Math.min(Math.max(cardCenter - left, 24), width - 24)}px`);
    }
