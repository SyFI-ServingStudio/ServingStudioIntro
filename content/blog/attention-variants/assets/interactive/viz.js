  function flowNoteLines(text, width) {
    if (!text) return 0;
    flowNoteContext ??= document.createElement("canvas").getContext("2d");
    flowNoteContext.font = "15px Geist, Arial, sans-serif";
    let lines = 1;
    let line = "";
    for (const word of String(text).replace(/_/g, "").split(/\s+/)) {
      const candidate = line ? `${line} ${word}` : word;
      if (line && flowNoteContext.measureText(candidate).width * 1.04 > width) {
        lines += 1;
        line = word;
      } else {
        line = candidate;
      }
    }
    return lines;
  }
  const FLOW_OLD_TOKENS = ["t0", "t1", "t2", "…", "t(L−1)"];
  // Cache cells and rows may be plain strings or objects with optional fields
  // (flows.js header comment); these normalize both forms.
  const flowCell = (cell) => (typeof cell === "string" ? { label: cell } : cell);
  const flowRow = (row) => (typeof row === "string" ? { label: row } : row);
  const FLOW_MODES = [["prefill", "Prefill"], ["decode", "Decode"]];
  // A field may differ by mode, { prefill, decode }, or follow the sliders: a function of `scale`.
  const byMode = (value, mode) =>
    value && typeof value === "object" && !Array.isArray(value) && "decode" in value ? value[mode] : value;
  const resolveField = (value, scale) => (typeof value === "function" ? value(scale) : byMode(value, scale.mode));

  // Sliders of an operand flow, per mode. Defaults: decode at batch 32 and 128K
  // (the decode figures' batch 32 and the context sliders' 128K); prefill a chunk
  // of 8,192 tokens, as the prefill section measures it, after a 128K prefix.
  const powersOfTwo = (from, to) => {
    const values = [];
    for (let value = from; value <= to; value *= 2) values.push(value);
    return values;
  };
  const flowTokensText = (tokens) =>
    tokens === 0 ? "0" : tokens % 1048576 === 0 ? `${tokens / 1048576}M` : tokens % 1024 === 0 ? `${(tokens / 1024).toLocaleString("en-US")}K` : tokens.toLocaleString("en-US");
  const FLOW_SLIDERS = {
    decode: [
      { key: "batch", label: "Batch B", steps: powersOfTwo(1, 256), initial: 32, format: (value) => String(value) },
      { key: "context", label: "Context L", steps: CONTEXTS, initial: 131072, format: flowTokensText },
    ],
    prefill: [
      { key: "chunk", label: "Chunk N", steps: powersOfTwo(1024, 16384), initial: 8192, format: (value) => value.toLocaleString("en-US") },
      { key: "context", label: "Prefix L", steps: [0, ...CONTEXTS], initial: 131072, format: flowTokensText },
    ],
  };
  const FLOW_OPERAND_GROUPS = [["input", "Input"], ["weight", "Weight"], ["cache", "Cache"], ["state", "State"], ["output", "Output"]];

  // Numbers on operand cards: FLOPs with a decimal prefix, bytes in binary units, intensity in FLOP/B.
  const flowFlopsText = (flops) => {
    if (flops === 0) return "0";
    for (const [scale, prefix] of [[1e15, "P"], [1e12, "T"], [1e9, "G"], [1e6, "M"], [1e3, "K"]]) {
      if (flops >= scale) return `${sig3(flops / scale)} ${prefix}FLOP`;
    }
    return `${sig3(flops)} FLOP`;
  };
  const flowIntensityText = (intensity) => (intensity >= 1000 ? Math.round(intensity).toLocaleString("en-US") : sig3(intensity));
  // "H_kv" → H with a subscript kv; plain text otherwise.
  function flowSymbol(text) {
    const fragment = document.createDocumentFragment();
    let last = 0;
    for (const match of text.matchAll(/_([A-Za-z0-9]+)/g)) {
      fragment.append(text.slice(last, match.index), element("sub", "", match[1]));
      last = match.index + match[0].length;
    }
    fragment.append(text.slice(last));
    return fragment;
  }
  // an HTML element whose text renders "_x" as a subscript
  const symbolElement = (tag, className, text) => {
    const node = element(tag, className);
    if (text != null) node.append(flowSymbol(String(text)));
    return node;
  };
  // the same for SVG text: "_x" becomes a lowered, smaller tspan
  function svgSymbolText(textNode, text) {
    let last = 0;
    for (const match of text.matchAll(/_([A-Za-z0-9]+)/g)) {
      if (match.index > last) textNode.append(text.slice(last, match.index));
      const sub = svgNode("tspan", { "baseline-shift": "sub", "font-size": "0.75em" }, match[1]);
      textNode.append(sub);
      last = match.index + match[0].length;
    }
    if (last < text.length) textNode.append(text.slice(last));
    return textNode;
  }
  const flowAxisValue = (dimension) => (dimension.tokens ? flowTokensText(dimension.size) : dimension.size.toLocaleString("en-US"));


  // A polyline with rounded corners.
  function roundedPath(points, radius) {
    let path = `M${points[0][0]},${points[0][1]}`;
    for (let index = 1; index < points.length - 1; index++) {
      const [px, py] = points[index - 1];
      const [cx, cy] = points[index];
      const [nx, ny] = points[index + 1];
      const inLength = Math.hypot(cx - px, cy - py);
      const outLength = Math.hypot(nx - cx, ny - cy);
      const r = Math.min(radius, inLength / 2, outLength / 2);
      const startX = cx - ((cx - px) / inLength) * r;
      const startY = cy - ((cy - py) / inLength) * r;
      const endX = cx + ((nx - cx) / outLength) * r;
      const endY = cy + ((ny - cy) / outLength) * r;
      path += ` L${startX},${startY} Q${cx},${cy} ${endX},${endY}`;
    }
    const [lastX, lastY] = points[points.length - 1];
    return `${path} L${lastX},${lastY}`;
  }

